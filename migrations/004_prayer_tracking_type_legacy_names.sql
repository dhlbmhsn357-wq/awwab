update worships
set tracking_type = 'prayer'
where category = 'prayer'
  and (
    legacy_key like 'prayer-fard:%'
    or name in (
      'صلاة الفجر','صلاة الظهر','صلاة العصر','صلاة المغرب','صلاة العشاء',
      'صلاة فجر','صلاة ظهر','صلاة عصر','صلاة مغرب','صلاة عشاء'
    )
  );
